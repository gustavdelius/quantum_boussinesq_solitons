def main():
    sea=read('twobody_toda_scan.json')['rows'];edge=read('twobody_toda_edge.json')['rows']
    assert len(sea)==14 and len(edge)==36
    base=sorted([r for r in sea if r['factor']==1],key=lambda r:-r['h'])
    refined=[r for r in sea if r['factor']!=1]
    sound=hfit(base,refined,'sound');sound['target']=3/(4*m.pi)
    assert abs(sound['value']-sound['target'])<sound['total_error']
    grid=[];comparisons=[]
    keys=['R12','R21','R_symmetric','R_antisymmetric','U12','U21','four12','endpoint_B12']
    for i,p in enumerate(base[0]['pairs']):
        row={k:p[k] for k in ['y1','y2','s1','s2']}
        row['r']=m.sqrt(m.mpf(str(p['y2']))/m.mpf(str(p['y1'])))
        row['quantities']={k:hfit(base,refined,k,i) for k in keys}
        if p['s2']==1:
            ee=next(e for e in edge if abs(m.mpf(e['y1'])-p['y1'])<m.mpf('1e-10') and abs(m.mpf(e['r'])-row['r'])<m.mpf('1e-10'))
            for key in ['R12','R21','R_symmetric','R_antisymmetric','U12','U21','four12']:
                fitv=row['quantities'][key];diff=abs(fitv['value']-m.mpf(ee[key]))
                comparisons.append(dict(y1=row['y1'],r=row['r'],key=key,difference=diff,budget=fitv['total_error']))
                assert diff<fitv['total_error'],comparisons[-1]
            fitv=row['quantities']['endpoint_B12'];target=m.mpf(ee['four_antisymmetric'])
            assert abs(fitv['value']-target)<fitv['total_error']
        else:
            for key in ['R12','R21','R_symmetric','R_antisymmetric','U12','U21','four12']:
                fitv=row['quantities'][key]
                assert abs(fitv['value'])<fitv['total_error'],(row['y1'],row['r'],key,fitv)
            ee=next(e for e in edge if abs(m.mpf(e['y1'])-p['y1'])<m.mpf('1e-10') and abs(m.mpf(e['r'])-row['r'])<m.mpf('1e-10'))
            fitv=row['quantities']['endpoint_B12'];target=(m.mpf(ee['B1'])-m.sqrt(m.pi))*(m.mpf(ee['B2'])-m.sqrt(m.pi))
            assert abs(fitv['value']-target)<fitv['total_error']
        grid.append(row)
    limits=[]
    for rtext in ['.25','.4','.5','.6','.75','.9']:
        r=m.mpf(rtext);rr=[e for e in edge if m.mpf(e['r'])==r]
        row=dict(r=r,forward=tailfit(rr,'R12'),symmetric=tailfit(rr,'R_symmetric'),antisymmetric=tailfit(rr,'R_antisymmetric'))
        chi=(m.polylog(2,r)-m.polylog(2,-r))/2
        targets=dict(forward=-4/m.pi*(chi-r),symmetric=2/m.pi*(r+1/r)-m.pi,
                     antisymmetric=m.pi-4/m.pi*chi+2/m.pi*(r-1/r))
        for key,target in targets.items():
            row[key]['target']=target;row[key]['discrepancy']=abs(row[key]['value']-target)
            assert row[key]['discrepancy']<row[key]['total_error'],(r,key,row[key])
        limits.append(row)
        row['head_on_directional_limit']=m.mpf(0)
        row['head_on_endpoint_B_constant_after_sqrtY_removal']=m.pi+2/m.pi*(r+1/r)
    # Restricted finite-dimensional candidate comparisons, no universal exclusion.
    rr=[r['r'] for r in limits];yy=[r['antisymmetric']['value'] for r in limits]
    bases={
        'chi2_plus_rational':[lambda r:1,lambda r:(m.polylog(2,r)-m.polylog(2,-r))/2,lambda r:r-1/r],
        'rational_three':[lambda r:1,lambda r:r,lambda r:1/r],
        'logs_three':[lambda r:1,lambda r:m.log(r),lambda r:m.log((1-r)/(1+r))],
        'log_product_three':[lambda r:1,lambda r:r-1/r,lambda r:m.log(r)*m.log((1-r)/(1+r))]}
    candidates={}
    for name,basis in bases.items():
        _,_,co,_=fit(rr,yy,basis)
        residuals=[sum(c*f(r) for c,f in zip(co,basis))-y for r,y in zip(rr,yy)]
        candidates[name]=dict(coefficients=list(co),maximum_residual=max(abs(v) for v in residuals),residuals=residuals)
    out=dict(status='Conditional Toda directional two-term edge coefficient. No identification with continuum Gamma-relative residual is asserted.',
        analytic_coefficients=dict(label='(c), conditional on corrected edge asymptotics',domain='0<r=beta2/beta1<1, right-moving ordered overtaking branch',
            chi2='(Li2(r)-Li2(-r))/2',forward='-4/pi*(chi2(r)-r)',symmetric='2/pi*(r+1/r)-pi',
            vartheta_N='pi-4/pi*chi2(r)+2/pi*(r-1/r)',reverse='forward-2*vartheta_N',
            head_on_directional='0',physical_scalar_identification='(d), not established',
            endpoint_B_overtaking='delta_classical+2*sqrt(pi*Y)*(1-r)+vartheta_N+O(Y^(-1/2))',
            endpoint_B_head_on='4*r*Y-2*sqrt(pi*Y)*(1+r)+pi+2/pi*(r+1/r)+O(Y^(-1/2))'),
        dictionary=dict(hbar_T='3 exp(-1/2) hbar_B',y='beta^2/hbar_B',r='beta2/beta1',
                        P_B='signed P0(kappa)/(6 sqrt(3) b)',kappa='sqrt(3) beta',phase='action_T/hbar_T = action_B/hbar_B'),
        definitions=dict(R12='[Phi(p1,p2)-Phi(p1,e2)-delta_T-C12]/hbar_T',
                         R_symmetric='(R12+R21)/2',vartheta='R_antisymmetric=(R12-R21)/2',
                         ordered_domain='right movers, beta1>beta2>0; exchange negates vartheta',
                         head_on='opposite edge, leading iterated small-amplitude coefficient zero',
                         finite_y='includes higher inverse-y orders; not a pure one-loop observable',
                         reference='four-term corrections and endpoint_B also provided explicitly'),
        sound=sound,finite_sea_grid=grid,halfline_grid=edge,semiclassical_limits=limits,candidates=candidates,
        finite_sea_vs_halfline=comparisons,
        runtime_seconds=dict(scan=sum(r['seconds'] for r in sea),edge=sum(r['seconds'] for r in edge)),
        error_scope='Mesh, h-fit and amplitude-fit spreads are deterministic diagnostics, not uniform error bounds. Physical identification, near-equal and vanishing ratio limits unproved.')
    (HERE/'twobody_toda_grid.json').write_text(json.dumps(out,indent=2,default=serial)+'\n')
    tables(out)
    for r in limits:
        v=r['antisymmetric'];print('r',r['r'],'vartheta',m.nstr(v['value'],16),'budget',m.nstr(v['total_error'],5),'discrepancy',m.nstr(v['discrepancy'],4))
    print('candidate residuals',[(n,m.nstr(v['maximum_residual'],4)) for n,v in candidates.items()])
    print('ALL CHECKS PASSED')

if __name__=='__main__':main()
