#!/usr/bin/env python3
"""Unconstrained fits, candidate tests, and coordinator-facing phase grid.
No theoretical intercept is supplied to a fit. All error estimates are
deterministic sensitivity diagnostics, not rigorous bounds or confidence levels.
"""
import json
from pathlib import Path
import mpmath as m
m.mp.dps=60
HERE=Path(__file__).resolve().parent
def read(name):return json.loads((HERE/name).read_text())
def fit(xs,ys,basis):
    X=m.matrix([[f(x) for f in basis] for x in xs]);v=m.matrix(ys)
    coeff=m.lu_solve(X.T*X,X.T*v)
    weights=list(((X.T*X)**-1*X.T)[0,:])
    return coeff[0],sum(abs(w) for w in weights),coeff,weights
def pol(n):return [lambda x,i=i:x**i for i in range(n+1)]
def hfit(base,refined,key,index=None):
    def val(row):return m.mpf(str(row[key] if index is None else row['pairs'][index][key]))
    grids=[('quartic7',7,pol(4)),('cubic6',6,pol(3)),('quintic8',8,pol(5)),('quad4',4,pol(2)),
           ('hlog7',7,pol(3)+[lambda x:x*m.log(x)]),('h2log7',7,pol(3)+[lambda x:x*x*m.log(x)])]
    fits=[]
    for name,n,basis in grids:
        rows=base[-n:];scale=m.mpf(str(rows[0]['h']))
        out=fit([m.mpf(str(r['h']))/scale for r in rows],[val(r) for r in rows],basis)
        fits.append(dict(name=name,value=out[0],weight_norm=out[1]))
    mesh=m.mpf('2e-10')
    for fine in refined:
        coarse=next(r for r in base if r['h']==fine['h'])
        mesh=max(mesh,abs(val(fine)-val(coarse))+m.mpf('2e-10'))
    center=fits[0]['value'];herr=max(abs(f['value']-center) for f in fits)
    merr=mesh*max(f['weight_norm'] for f in fits)
    return dict(value=center,h_error=herr,mesh_error=merr,total_error=herr+merr,variants=fits)
def tailfit(rows,key):
    rows=sorted(rows,key=lambda r:m.mpf(r['y1']))
    n=len(rows)
    variants=[('quadratic3',3,pol(2)),('linear2',2,pol(1))]
    if n>=5:
        variants=[('cubic4',4,pol(3)),('quadratic3',3,pol(2)),('quadratic4',4,pol(2)),
                  ('halfpower4',4,[lambda x:1,lambda x:x,lambda x:x**m.mpf('1.5'),lambda x:x*x]),
                  ('x2log5',5,pol(3)+[lambda x:x*x*m.log(x)]),('linear2',2,pol(1))]
    vals=[]
    for name,n,basis in variants:
        rr=rows[-n:];scale=m.mpf(rr[-1]['y1'])
        value,wn,coeff,weights=fit([scale/m.mpf(r['y1']) for r in rr],[m.mpf(r[key]) for r in rr],basis)
        qerr=sum(abs(w)*m.mpf(r['quadrature_difference']) for w,r in zip(weights,rr))+m.mpf('1e-24')
        vals.append(dict(name=name,value=value,quadrature_error=qerr,weight_norm=wn))
    center=vals[0]['value'];tail=max(abs(v['value']-center) for v in vals)
    quad=max(v['quadrature_error'] for v in vals)
    return dict(value=center,tail_error=tail,quadrature_error=quad,total_error=tail+quad,variants=vals)
def serial(o):
    if isinstance(o,m.mpf):return m.nstr(o,35)
    raise TypeError(type(o))
def latexnum(x,digits=8):
    x=float(x)
    if x==0:return '0'
    if abs(x)<1e-4:
        a,b=f'{x:.2e}'.split('e');return a+r'\,10^{'+str(int(b))+'}'
    return f'{x:.{digits}f}'
